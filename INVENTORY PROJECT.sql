--Function to insert record into Order table with autogeneration of OID
CREATE PROCEDURE INORD @CI AS CHAR(5), @PI AS CHAR(5), @QT AS INT
AS
BEGIN
	DECLARE @I AS INT;
	DECLARE  @ID AS CHAR (5);

	SET @I = (NEXT VALUE FOR S4);
	SET @ID = DBO.CID('O', @I);

	INSERT INTO ORDERS
	VALUES(@ID, GETDATE(), @CI, @PI, @QT);

	SELECT * FROM ORDERS;
	SELECT * FROM STOCK WHERE PID = @PI;
END;

--Creation of trigger which checks the stock before placing order and update the stock quantity after placing the order if stock avaialable
CREATE TRIGGER TR_IN_ORD
ON ORDERS 
FOR INSERT
AS
BEGIN
	SET NOCOUNT ON;
	DECLARE @QR AS INT;
	DECLARE @QS AS INT;

	SET @QR = (SELECT OQTY FROM INSERTED);
	SET @QS = (SELECT SQTY FROM STOCK WHERE PID = (SELECT PID FROM INSERTED));

	IF @QS >= @QR	
		BEGIN
			UPDATE STOCK SET SQTY = SQTY - (SELECT OQTY FROM INSERTED)
			WHERE PID = (SELECT PID FROM INSERTED);
			COMMIT;
			PRINT ('ORDER ACCEPTED');
		END;
	ELSE
		BEGIN
			ROLLBACK;
			PRINT('INSUFFICIENT QUANTITY ORDER REJECTED');
		END;

END;

