--Function to automatically generate alphanumeric ID of length 5 character eg:C0001
CREATE FUNCTION CID (@C AS CHAR(1), @I AS INT)
RETURNS CHAR(5)
AS
BEGIN
	DECLARE @ID AS CHAR(5);
	IF @I < 10 
		SET @ID = CONCAT (@C, '000', @I)
	ELSE IF @I < 100
		SET @ID = CONCAT (@C, '00', @I)
	ELSE IF @I < 1000 
		SET @ID = CONCAT (@C, '0', @I)
	ELSE IF @I < 10000
		SET @ID = CONCAT (@C, @I)
	ELSE
		SET @ID = 'NA';
	RETURN @ID;

END;

