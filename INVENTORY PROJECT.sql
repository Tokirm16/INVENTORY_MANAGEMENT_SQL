--Function to make supplier report which show all products details listed by supplier.

CREATE PROCEDURE SUPREP @SID AS CHAR(5)
AS
BEGIN
    SELECT S.SID, PID, PDESC, PRICE, CATEGORY  FROM PRODUCT P
	INNER JOIN SUPPLIER S
	ON P.SID = S.SID
	WHERE S.SID = @SID;

END;


