-- Function to generate bill report for a perticular Order ID
CREATE PROCEDURE BILL @OI AS CHAR(5)
AS
BEGIN
	SELECT CUSTOMER.CID, CNAME, OID, ODATE , PRODUCT.PID, PDESC, PRICE, OQTY , PRICE * OQTY AS 'AMOUNT'
	FROM ORDERS
	INNER JOIN CUSTOMER
	ON ORDERS.CID = CUSTOMER.CID
	INNER JOIN PRODUCT
	ON ORDERS.PID = PRODUCT.PID
	WHERE OID = @OI;
END;


--Function to generate customer cleasure(All transaction done by that customer)

CREATE PROCEDURE CUSTREP @CID AS CHAR(5)
AS
BEGIN
    SELECT C.CID,C.CNAME,OID,ODATE,O.PID PDESC,OQTY, PRICE, OQTY*PRICE AS 'AMOUNT'
	FROM CUSTOMER C
	INNER JOIN ORDERS O
	ON C.CID = O.CID
	INNER JOIN PRODUCT P
	ON P.PID = O.PID
	WHERE C.CID = @CID;

END;

